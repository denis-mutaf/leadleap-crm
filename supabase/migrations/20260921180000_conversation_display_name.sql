-- Переписка из мессенджера приходит с именем профиля, но без телефона, и
-- сопоставить её с контактом по одному имени нельзя: в базе 1250 тёзок.
-- Имя хранится прямо на переписке, чтобы инбокс было чем подписать, пока
-- менеджер не привязал тред к карточке вручную.
alter table public.conversations
  add column if not exists display_name text;

comment on column public.conversations.display_name is
  'Имя собеседника из мессенджера. Показывается, пока contact_id пуст.';
